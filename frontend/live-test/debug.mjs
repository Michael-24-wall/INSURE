import { chromium } from "playwright";
const BASE = "http://127.0.0.1:5173";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await (await browser.newContext()).newPage();
await page.goto(BASE + "/login", { waitUntil: "networkidle" });
await page.getByRole("textbox", { name: /^Email address/ }).fill("customer@example.com");
await page.getByRole("textbox", { name: /^Password/ }).fill("Customer@12345");
await page.getByRole("button", { name: "Sign in", exact: true }).click();
await page.waitForURL(/\/app/);
await page.goto(BASE + "/app/vehicles", { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Add vehicle" }).click();
await page.waitForTimeout(500);
const labels = await page.locator("label").evaluateAll((els) => els.map((e) => e.textContent.trim()));
console.log("LABELS:", JSON.stringify(labels));
const makes = await page.getByLabel("Make").count();
console.log("getByLabel('Make') count:", makes);
const el = await page.getByLabel("Make").evaluateAll((els) => els.map((e) => `${e.tagName}#${e.id} aria=${e.getAttribute('aria-label')} value="${e.value}"`));
console.log("matches:", JSON.stringify(el, null, 2));
await browser.close();
